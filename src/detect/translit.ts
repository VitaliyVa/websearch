/**
 * Транслітерація кирилиці та нормалізація написань.
 *
 * Задача: звести «Віталій», «Виталий», «Vitalii», «Vitaliy», «Vitaly» до
 * ОДНОГО ключа. Перелічувати варіанти кожного імені неможливо — Щербицький
 * має щонайменше десяток латинських написань, і список став би некерованим.
 * Тому нормалізуємо, а в базі тримаємо канонічну форму.
 */

/** Багатолітерні відповідники мають іти ПЕРШИМИ, інакше «щ» розпадеться на «ш»+«ч». */
const CYRILLIC_MAP: [RegExp, string][] = [
  [/щ/g, 'shch'], [/Щ/g, 'shch'],
  [/ж/g, 'zh'], [/Ж/g, 'zh'],
  [/ч/g, 'ch'], [/Ч/g, 'ch'],
  [/ш/g, 'sh'], [/Ш/g, 'sh'],
  [/ю/g, 'iu'], [/Ю/g, 'iu'],
  [/я/g, 'ia'], [/Я/g, 'ia'],
  [/є/g, 'ie'], [/Є/g, 'ie'],
  [/ї/g, 'i'], [/Ї/g, 'i'],
  [/х/g, 'kh'], [/Х/g, 'kh'],
  [/ц/g, 'ts'], [/Ц/g, 'ts'],
  [/ё/g, 'io'], [/Ё/g, 'io'],
  [/а/g, 'a'], [/А/g, 'a'],
  [/б/g, 'b'], [/Б/g, 'b'],
  [/в/g, 'v'], [/В/g, 'v'],
  [/г/g, 'h'], [/Г/g, 'h'],
  [/ґ/g, 'g'], [/Ґ/g, 'g'],
  [/д/g, 'd'], [/Д/g, 'd'],
  [/е/g, 'e'], [/Е/g, 'e'],
  [/з/g, 'z'], [/З/g, 'z'],
  [/и/g, 'y'], [/И/g, 'y'],
  [/і/g, 'i'], [/І/g, 'i'],
  [/й/g, 'i'], [/Й/g, 'i'],
  [/к/g, 'k'], [/К/g, 'k'],
  [/л/g, 'l'], [/Л/g, 'l'],
  [/м/g, 'm'], [/М/g, 'm'],
  [/н/g, 'n'], [/Н/g, 'n'],
  [/о/g, 'o'], [/О/g, 'o'],
  [/п/g, 'p'], [/П/g, 'p'],
  [/р/g, 'r'], [/Р/g, 'r'],
  [/с/g, 's'], [/С/g, 's'],
  [/т/g, 't'], [/Т/g, 't'],
  [/у/g, 'u'], [/У/g, 'u'],
  [/ф/g, 'f'], [/Ф/g, 'f'],
  [/ы/g, 'y'], [/Ы/g, 'y'],
  [/э/g, 'e'], [/Э/g, 'e'],
  [/ь/g, ''], [/Ь/g, ''],
  [/ъ/g, ''], [/Ъ/g, ''],
  [/'/g, ''], [/’/g, ''],
];

export const hasCyrillic = (s: string) => /[Ѐ-ӿ]/.test(s);

export function cyrillicToLatin(input: string): string {
  let out = input;
  for (const [re, to] of CYRILLIC_MAP) out = out.replace(re, to);
  return out;
}

/**
 * Класи еквівалентності транслітерації.
 *
 * СВІДОМО КОНСЕРВАТИВНІ. Кожне зайве злиття збільшує шанс, що англійське
 * прізвище випадково збіжиться зі слов'янським. Наприклад, спокуса звести
 * «c» до «ts» відкинута: тоді Cook → tsook, а користі нуль.
 */
/**
 * Латинські літери з діакритикою — мапимо ДО зняття діакритики.
 *
 * Без цього польське «Kozłowski» перетворювалось на «kozowski»: ł не є
 * l+діакритика, це окрема літера, і NFD її не розкладає, а фільтр [^a-z]
 * просто викидав. Через це польські прізвища не збігалися зі списком
 * виключень — тобто поляки проходили далі.
 * Так само š/č/ž втрачали свою природу диграфів раніше, ніж правила
 * встигали їх обробити.
 */
const LATIN_DIACRITICS: [RegExp, string][] = [
  [/š/g, 'sh'], [/č/g, 'ch'], [/ž/g, 'zh'],
  [/ł/g, 'l'], [/ć/g, 'ts'], [/ś/g, 's'], [/ź|ż/g, 'z'],
  [/ń/g, 'n'], [/ą/g, 'a'], [/ę/g, 'e'], [/ó/g, 'o'],
  [/ř/g, 'r'], [/ů/g, 'u'], [/ě/g, 'e'], [/ť/g, 't'], [/ď/g, 'd'], [/ň/g, 'n'],
  [/ý/g, 'y'], [/á/g, 'a'], [/í/g, 'i'], [/é/g, 'e'], [/ú/g, 'u'],
];

const NORMALIZE_RULES: [RegExp, string][] = [
  // диграфи спершу — довші шаблони раніше за короткі
  [/shch|sczc|stch|sch(?=[aeiouy])/g, 'X'], // X — тимчасовий маркер для щ
  /*
   * sz і cz СВІДОМО не зводяться до sh/ch.
   *
   * Це польська орфографія, і саме написання несе сигнал: Bondarczuk —
   * польський запис, Bondarchuk — український. Зливаючи їх, ми стирали рівно
   * ту різницю, яку хочемо ловити, і українське прізвище отримувало вердикт
   * «польське». Українці в США пишуться через ch/sh, тож втрати мінімальні.
   */
  [/š/g, 'sh'],
  [/tch|č/g, 'ch'],
  [/ž/g, 'zh'],
  [/kh|х/g, 'h'],          // Х і Г зливаємо: Horbach/Khorbach — той самий пошук
  [/ck/g, 'k'],            // Bicko / Bitsko
  [/ff\b/g, 'v'],          // Sverdloff → sverdlov
  /*
   * w → v СВІДОМО прибрано, з тієї ж причини, що cz і sz.
   *
   * Польська орфографія використовує w там, де східнослов'янська
   * транслітерація дає v: Sładkowski проти Sladkovskii. Зливаючи їх, ми
   * втрачали справжні прізвища — на живих даних так загубився
   * Nikita Sladkovskii, бо збігся з польським ключем.
   *
   * Ціна: рідкісні написання через w (Kowalenko) більше не збігаються з
   * Kovalenko. Для Чикаго, де польська громада більша за українську,
   * це вигідний обмін.
   */
  [/j(?=[aeiou])/g, 'i'],  // Jurij → iurii
  [/ya|ja/g, 'ia'],
  [/yu|ju/g, 'iu'],
  [/ye|je/g, 'ie'],
  [/yo|jo/g, 'io'],
  [/X/g, 'shch'],          // повертаємо маркер
  // голосні на кінці: -ii/-iy/-yi/-y/-ij/-i → i
  [/(ii|iy|yi|ij|yj|y|j)$/g, 'i'],
  /*
   * y → i всередині слова: укр «и» і «і» транслітерують по-різному в різних
   * системах, тому Melnyk і Melnik — те саме прізвище. Ризик колізій з
   * англійськими (Smyth→smith, Lynch→linch) прийнятний: обидва варіанти
   * лишаються англійськими, а отже хибного спрацювання не дають.
   */
  [/y/g, 'i'],
  // подвоєння будь-яких літер
  [/(.)\1+/g, '$1'],
];

/**
 * Канонічна форма імені. Застосовується І до бази, І до вхідних імен —
 * тільки так Vitalii і Vitaliy зустрінуться в одній точці.
 */
export function normalizeName(input: string): string {
  let s = input.trim().toLowerCase();
  if (hasCyrillic(s)) s = cyrillicToLatin(s);

  // Спершу літери-диграфи (š→sh) і польські (ł→l), і лише потім NFD:
  // інакше вони або втрачають природу диграфа, або зникають зовсім
  for (const [re, to] of LATIN_DIACRITICS) s = s.replace(re, to);

  s = s
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '') // залишкова діакритика
    .replace(/[^a-z]/g, '');

  for (const [re, to] of NORMALIZE_RULES) s = s.replace(re, to);
  return s;
}
